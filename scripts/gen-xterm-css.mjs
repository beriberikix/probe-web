#!/usr/bin/env node
// Write packages/ui/src/xterm-css.generated.ts from the installed xterm stylesheet.
//
// The terminal elements put xterm's CSS in their shadow roots, so they need it as a string.
// Asking the bundler for one (`import css from '@xterm/xterm/css/xterm.css?inline'`) is a
// Vite-only spelling: webpack and Rollup cannot resolve that query, which would keep
// @probe-web/ui a Vite-only package for no reason other than how it reads a stylesheet.
// Committing the string instead makes the package work on any bundler.
//
// The cost is that the copy can drift from the installed xterm, so CI regenerates it and
// fails if the result differs — the same guard `packages/client/src/wire.ts` has.
//
//   node scripts/gen-xterm-css.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = new URL('node_modules/@xterm/xterm/css/xterm.css', root);
const target = new URL('packages/ui/src/xterm-css.generated.ts', root);
const version = JSON.parse(await readFile(new URL('node_modules/@xterm/xterm/package.json', root), 'utf8')).version;

const css = await readFile(source, 'utf8');
// Only the three sequences a template literal can misread; xterm's stylesheet contains none
// of them today, but it is not this script's business to assume that stays true.
const escaped = css.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

await writeFile(target, `// Generated by scripts/gen-xterm-css.mjs from @xterm/xterm@${version}. Do not edit.
// Regenerate after upgrading xterm; CI fails if this file is stale.
export default \`${escaped}\`;
`);

console.log(`${fileURLToPath(target)} <- @xterm/xterm@${version} (${css.length} bytes)`);
